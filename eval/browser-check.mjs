// Run explicitly with PLAYWRIGHT_MODULE pointing to an installed playwright module.
// This check uses simulated API responses; it never spends API credits.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { createAppServer } from '../server.mjs';

const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const pieces = { jev: [], decisions: [] };
let failJev = false;
const server = createAppServer({ apiKey: 'mock-jev', openaiKey: 'mock-openai', fetchImpl: async (url, init) => {
  const body = JSON.parse(init.body), openai = url.includes('openai');
  const shared = openai ? JSON.parse(body.input) : body.state;
  const provider = openai ? 'decisions' : 'jev'; pieces[provider].push(shared.current_piece);
  await new Promise((resolve, reject) => {
    const timer = setTimeout(resolve, openai ? 20 : 180);
    init.signal.addEventListener('abort', () => { clearTimeout(timer); reject(init.signal.reason); }, { once: true });
  });
  if (!openai && failJev) return new Response('', { status: 429 });
  const criteria = openai ? Object.fromEntries(body.questions[0].choices.map(c => [c.value, JSON.parse(c.description)])) : body.questions.placement.criteria;
  const ids = Object.keys(criteria);
  const number = (text, pattern) => Number(text.match(pattern)?.[1] || 0);
  const rating = c => number(c.buried_empty_cells, /Leaves (\d+)/) * 100 + number(c.headroom, /is (\d+)/) * 3 + number(c.surface, /sum to (\d+)/) - number(c.row_clears, /clears (\d+)/) * 10;
  const choice = ids.reduce((a, b) => rating(criteria[a]) <= rating(criteria[b]) ? a : b);
  const answer = { type: 'choice', choice, confidence: 1, probabilities: Object.fromEntries(ids.map(id => [id, id === choice ? 1 : 0])) };
  return Response.json({ model: openai ? 'gpt-6-luna' : 'jev-1.13.0', answers: openai ? [{ ...answer, name: 'placement', probabilities: ids.map(value => ({ value, probability: value === choice ? 1 : 0 })) }] : { placement: answer }, usage: { input_tokens: 100, output_tokens: 0 } });
} });
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.waitForFunction(() => !document.querySelector('#jev-play').disabled && !document.querySelector('#decisions-play').disabled);
  assert.equal(await page.locator('canvas').count(), 2);
  assert.equal(await page.evaluate(() => { const ids = [...document.querySelectorAll('[id]')].map(e => e.id); return ids.length === new Set(ids).size; }), true);
  await page.locator('#play-both').click();
  await page.waitForFunction(() => Number(document.querySelector('#decisions-compare-pieces').textContent) >= 8);
  assert.ok(Number(await page.locator('#jev-compare-pieces').textContent()) < Number(await page.locator('#decisions-compare-pieces').textContent()));
  await page.locator('#play-both').click();
  const paused = await page.locator('#decisions-compare-pieces').textContent();
  await page.waitForTimeout(250);
  assert.equal(await page.locator('#decisions-compare-pieces').textContent(), paused);
  assert.deepEqual(pieces.jev, pieces.decisions.slice(0, pieces.jev.length));
  for (const provider of ['jev', 'decisions']) {
    assert.ok(await page.locator('#' + provider + '-cost').isVisible());
    assert.ok(await page.locator('#' + provider + '-compare-cost').isVisible());
    const stored = await page.evaluate(p => JSON.parse(sessionStorage.getItem(p + '-cost-v1')), provider);
    assert.ok(stored.usd > 0);
    assert.equal(await page.locator('#' + provider + '-compare-cost').textContent(), await page.locator('#' + provider + '-cost').textContent());
  }
  assert.match(await page.locator('#decisions-leader').textContent(), /응답 빠름/);
  await mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/comparison-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  assert.ok((await page.locator('#play-both').boundingBox()).height < 60);
  await page.screenshot({ path: 'artifacts/comparison-mobile.png', fullPage: true });
  assert.ok(await page.locator('#decisions-compare-cost').isVisible());
  await page.locator('#decisions-reset-cost').click();
  assert.equal(await page.locator('#decisions-compare-cost').textContent(), '$0.0000');
  const retainedJevCost = await page.locator('#jev-compare-cost').textContent();
  await page.reload();
  await page.waitForFunction(() => !document.querySelector('#jev-play').disabled && !document.querySelector('#decisions-play').disabled);
  assert.equal(await page.locator('#decisions-compare-cost').textContent(), '$0.0000');
  assert.equal(await page.locator('#jev-compare-cost').textContent(), retainedJevCost);
  await page.setViewportSize({ width: 320, height: 740 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.locator('#reset-both').click();
  assert.equal(await page.locator('#jev-compare-pieces').textContent(), '0');
  assert.equal(await page.locator('#decisions-compare-pieces').textContent(), '0');
  assert.equal(await page.locator('#jev-compare-average').textContent(), '—');
  failJev = true;
  await page.locator('#play-both').click();
  await page.waitForFunction(() => document.querySelector('#jev-compare-phase').textContent === '연결 오류');
  const before = Number(await page.locator('#decisions-compare-pieces').textContent());
  await page.waitForFunction(n => Number(document.querySelector('#decisions-compare-pieces').textContent) > n, before);
  await page.locator('#play-both').click();
  assert.equal(await page.locator('#result-dialog').evaluate(el => el.open), false);
  await page.locator('#reset-both').click();
  failJev = false;
  await page.locator('#pace').selectOption('gravity');
  await page.locator('#play-both').click();
  await page.waitForFunction(() => Number(document.querySelector('#jev-compare-pieces').textContent) >= 1 && Number(document.querySelector('#decisions-compare-pieces').textContent) >= 1);
  await page.locator('#play-both').click();
  await page.locator('#reset-both').click();
  await page.locator('#pace').selectOption('response');
  await page.locator('#turn-limit').selectOption('25');
  await page.locator('#play-both').click();
  await page.waitForFunction(() => document.querySelector('#decisions-compare-phase').textContent === '한도 도달');
  assert.equal(await page.locator('#result-dialog').evaluate(el => el.open), false, 'fast player must wait for the other result');
  await page.waitForFunction(() => document.querySelector('#result-dialog').open);
  assert.equal(await page.locator('#jev-compare-phase').textContent(), '한도 도달');
  assert.equal(await page.locator('#decisions-compare-phase').textContent(), '한도 도달');
  const resultRows = page.locator('#result-rows tr');
  assert.equal(await resultRows.filter({ has: page.locator('th', { hasText: '배치 블록' }) }).locator('td').first().textContent(), '25개');
  assert.equal(await resultRows.filter({ has: page.locator('th', { hasText: '배치 블록' }) }).locator('td').last().textContent(), '25개');
  assert.equal(await page.locator('#result-speed-leader').textContent(), 'Decisions');
  const gameCostRow = resultRows.filter({ has: page.locator('th', { hasText: '이번 게임 예상 비용' }) });
  assert.equal(await gameCostRow.locator('td').first().textContent(), '$0.0001');
  assert.equal(await gameCostRow.locator('td').last().textContent(), '$0.0003');
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.screenshot({ path: 'artifacts/comparison-result-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'artifacts/comparison-result-mobile.png' });
  await page.locator('#result-close').click();
  await page.waitForTimeout(1200);
  assert.equal(await page.locator('#result-dialog').evaluate(el => el.open), false, 'closing the result must keep it closed');
  await page.locator('#show-result').click();
  assert.equal(await page.locator('#result-dialog').evaluate(el => el.open), true);
  await page.locator('#result-new-game').click();
  assert.equal(await page.locator('#result-dialog').evaluate(el => el.open), false);
  assert.equal(await page.locator('#jev-compare-pieces').textContent(), '0');
  assert.equal(await page.locator('#decisions-compare-pieces').textContent(), '0');
  assert.equal(await page.locator('#show-result').isVisible(), false);
  failJev = true;
  await page.locator('#play-both').click();
  await page.waitForFunction(() => document.querySelector('#result-dialog').open);
  assert.match(await page.locator('#result-note').textContent(), /먼저 멈췄/);
  assert.match(await page.locator('#result-errors').textContent(), /JEV:/);
  assert.equal(await page.locator('#decisions-compare-phase').textContent(), '한도 도달');
  assert.deepEqual(errors, []);
  console.log('Browser check passed: cadence, sequence, pause/reset, costs, gravity, result modal timing, per-game costs, close/reopen/new game, early errors and mobile layout.');
} finally {
  await browser?.close();
  await new Promise(resolve => server.close(resolve));
}
